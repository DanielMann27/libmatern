#!/bin/bash
# extract_upstream.sh -- generates cpu_bessels_data.h from ../upstream/constants.jl and
# ../upstream/U_polynomials.jl (fetched by make references), copying every literal unchanged
# after checking both sources against the sha256 digests in ../PROVENANCE.md.
set -euo pipefail
cd "$(dirname "$0")"
U=../upstream
OUT=cpu_bessels_data.h
DOC=../PROVENANCE.md

# recorded <file>: the 64-hex-digit cell of the PROVENANCE.md row whose first cell is
# `<file>`.
recorded() {
    awk -F'|' -v f="\`$1\`" '{ c = $2; gsub(/ /, "", c) } c == f {
        for (i = 3; i <= NF; i++) { h = $i; gsub(/[` ]/, "", h)
            if (length(h) == 64 && h ~ /^[0-9a-f]+$/) { print h; exit } } }' "$DOC"
}
for f in constants.jl U_polynomials.jl; do
    [ -s "$U/$f" ] || { echo "extract_upstream.sh: missing $U/$f (make references)" >&2; exit 1; }
    want=$(recorded "$f")
    [ -n "$want" ] || { echo "extract_upstream.sh: no sha256 for $f in $DOC" >&2; exit 1; }
    got=$(sha256sum "$U/$f" | cut -d' ' -f1)
    if [ "$got" != "$want" ]; then
        echo "extract_upstream.sh: $U/$f is not the recorded file (sha256 $got," \
             "recorded $want); run make references" >&2
        exit 1
    fi
done

python3 - "$U" "$OUT" <<'PY'
import re, sys
udir, out = sys.argv[1], sys.argv[2]
consts = open(f"{udir}/constants.jl").read()
upoly  = open(f"{udir}/U_polynomials.jl").read()

def jl2c(tok):
    """Julia float literal -> C double literal.  Float32 ('f') is rejected."""
    tok = tok.strip()
    if 'f' in tok:
        raise ValueError("Float32 literal reached the Float64 extractor: " + tok)
    return tok

def tuple_f64(name, text):
    """const NAME(::Type{Float64}) = ( ... )  ->  list of C literals."""
    m = re.search(r'const\s+' + re.escape(name) +
                  r'\(::Type\{Float64\}\)\s*=\s*\((.*?)\)', text, re.S)
    if not m:
        raise KeyError(name)
    return [jl2c(t) for t in m.group(1).replace('\n', ' ').split(',') if t.strip()]

def scalar_f64(name, text):
    m = re.search(r'const\s+' + re.escape(name) +
                  r'\(::Type\{Float64\}\)\s*=\s*([^\s\n]+)', text, re.S)
    if m:
        return jl2c(m.group(1))
    m = re.search(r'const\s+' + re.escape(name) + r'\s*=\s*([^\s\n]+)', text, re.S)
    if not m:
        raise KeyError(name)
    return jl2c(m.group(1))

def upoly_row(k, text):
    """u<k> = evalpoly(p2, ( ... )) inside Uk_poly10(p2)."""
    body = re.search(r'function Uk_poly10\(p2\)(.*?)\n end|function Uk_poly10\(p2\)(.*?)return',
                     text, re.S)
    body = body.group(1) or body.group(2)
    m = re.search(r'\bu%d\s*=\s*evalpoly\(p2,\s*\((.*?)\)\)' % k, body, re.S)
    if not m:
        raise KeyError("u%d" % k)
    return [jl2c(t) for t in m.group(1).replace('\n', ' ').split(',') if t.strip()]

tables, scalars, n = [], [], 0
for nm in ("P1_k0","Q1_k0","P2_k0","P3_k0","Q3_k0",
           "P1_k1","Q1_k1","P2_k1","Q2_k1","P3_k1","Q3_k1"):
    tables.append((nm, tuple_f64(nm, consts))); n += 1
for nm in ("Y_k0","Y_k1","Y2_k1"):
    scalars.append((nm, scalar_f64(nm, consts))); n += 1
for k in range(1, 11):
    tables.append(("BJL_U%d" % k, upoly_row(k, upoly))); n += 1

if n != 24:
    sys.exit("extract_upstream.sh: expected 24 tables/scalars, extracted %d" % n)

w = open(out, "w")
w.write("""/* GENERATED by extract_upstream.sh -- DO NOT EDIT.
 *
 * Coefficient tables copied verbatim out of Bessels.jl (MIT, see
 * references/bessels_jl/LICENSE):
 *   src/BesselFunctions/constants.jl       -- K0/K1 rational approximations
 *                                             (themselves from boost.math)
 *   src/BesselFunctions/U_polynomials.jl   -- Debye u_1..u_10 in p2 = p^2
 *
 * Every literal below is the upstream text unchanged; the only transformation is
 * Julia tuple syntax -> C array syntax.  Regenerate with ./extract_upstream.sh.
 */
#ifndef CPU_BESSELS_DATA_H
#define CPU_BESSELS_DATA_H

""")
for nm, v in tables:
    w.write("static const double %s[%d] = {\n" % (nm, len(v)))
    for i in range(0, len(v), 3):
        w.write("    " + ", ".join(v[i:i+3]) + ("," if i+3 < len(v) else "") + "\n")
    w.write("};\n")
    w.write("#define %s_N %d\n\n" % (nm, len(v)))
for nm, v in scalars:
    w.write("#define %s (%s)\n" % (nm, v))
w.write("\n#endif /* CPU_BESSELS_DATA_H */\n")
w.close()
print("cpu_bessels_data.h: %d tables + %d scalars" % (len(tables), len(scalars)))
PY

grep -c 'static const double' "$OUT"
